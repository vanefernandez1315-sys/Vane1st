create table if not exists public.food_cost_workspaces (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  workspace_key text not null default 'foodcost-control-v1',
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint food_cost_workspaces_user_workspace_unique unique (user_id, workspace_key),
  constraint food_cost_workspaces_key_check check (workspace_key = 'foodcost-control-v1'),
  constraint food_cost_workspaces_data_object check (jsonb_typeof(data) = 'object')
);
create index if not exists food_cost_workspaces_user_id_idx on public.food_cost_workspaces(user_id);
alter table public.food_cost_workspaces enable row level security;
alter table public.food_cost_workspaces force row level security;
drop policy if exists "Users can read own Food Cost workspace" on public.food_cost_workspaces;
drop policy if exists "Users can insert own Food Cost workspace" on public.food_cost_workspaces;
drop policy if exists "Users can update own Food Cost workspace" on public.food_cost_workspaces;
drop policy if exists "Users can delete own Food Cost workspace" on public.food_cost_workspaces;
create policy "Users can read own Food Cost workspace" on public.food_cost_workspaces for select to authenticated using (auth.uid() = user_id);
create policy "Users can insert own Food Cost workspace" on public.food_cost_workspaces for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can update own Food Cost workspace" on public.food_cost_workspaces for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete own Food Cost workspace" on public.food_cost_workspaces for delete to authenticated using (auth.uid() = user_id);
grant select, insert, update, delete on public.food_cost_workspaces to authenticated;
grant usage, select on sequence public.food_cost_workspaces_id_seq to authenticated;